def _slug(text: str) -> str:
    return re.sub(r"[^0-9a-z]+", "_", text.lower()).strip("_")


def _toy_matrices() -> dict[str, Any]:
    return {
        "VA": CustomTensor(
            (3,),
            2,
            level=SparseLevel(
                1,
                ElementLevel(np.ones(2, dtype=np.int64)),
                (np.array([0, 2]),),
            ),
        ),
        "VB": CustomTensor(
            (3,),
            1,
            level=SparseLevel(
                1,
                ElementLevel(np.ones(1, dtype=np.int64)),
                (np.array([1]),),
            ),
        ),
        "E0": COORMatrix(
            (3, 3),
            3,
            indices_0=np.array([0, 0, 2]),
            indices_1=np.array([1, 2, 1]),
            values=np.ones(3, dtype=np.int64),
        ),
    }


def gcare_query(subset: str, query_name: str) -> tuple[dict[str, Any], DataInstance]:
    """Return ``(query, graph_problem)`` for a query of a cached G-CARE graph.

    ``query`` holds the parsed ``"expr"``, sorted ``"matrix_names"`` and ``"gt"``.
    """
    raw_generator = GCareGraphGenerator()
    raw_dataset = next(
        (ds for ds in raw_generator.datasets if ds.name == subset),
        None,
    )
    if raw_dataset is None:
        raise ValueError(
            f"Dataset {subset!r} is not listed in GCareGraphGenerator.datasets."
        )
    graph_problem = raw_generator.cached_generate(raw_dataset)
    graph_meta = graph_problem.meta
    if "queries" not in graph_meta:
        raise RuntimeError(
            f"Cached G-CARE graph {subset!r} has no query metadata. "
            "Refresh it with --cache-datasets --re '^subgraph_gcare_graph$'."
        )
    if query_name not in graph_meta["queries"]:
        raise ValueError(
            f"Query {subset}/{query_name} is not in the cached G-CARE queries."
        )
    return graph_meta["queries"][query_name], graph_problem


def _gcare_query_inputs(subset, query_name, matrix_names):
    query, graph_problem = gcare_query(subset, query_name)
    if sorted(matrix_names) != sorted(query["matrix_names"]):
        raise RuntimeError(
            f"G-CARE query {subset}/{query_name} uses {query['matrix_names']}, but "
            f"its benchmark takes {list(matrix_names)}. Regenerate the subgraph "
            "benchmarks with ./bin/generate_subgraph_benchmarks.py."
        )
    graph_meta = graph_problem.meta
    graph_matrices = dict(
        zip(graph_meta["matrix_names"], graph_problem.inputs, strict=True)
    )
    size = graph_meta["max_vid"] + 1
    inputs = []
    for name in matrix_names:
        if name in graph_matrices:
            tensor = graph_matrices[name]
        elif name.startswith("P"):
            tensor = CustomTensor(
                (size,),
                1,
                level=SparseLevel(
                    1,
                    ElementLevel(np.array([1])),
                    (np.array([int(name[1:])]),),
                ),
            )
        elif name.startswith("V"):
            tensor = CustomTensor(
                (size,),
                1,
                level=SparseLevel(1, ElementLevel(np.array([0])), (np.array([0]),)),
            )
        elif name.startswith("E"):
            tensor = COORMatrix(
                (size, size),
                1,
                indices_0=np.array([0]),
                indices_1=np.array([0]),
                values=np.array([0]),
            )
        else:
            raise ValueError(f"Cached G-CARE graph is missing matrix {name!r}")
        inputs.append(tensor)
    return inputs, query["gt"]


