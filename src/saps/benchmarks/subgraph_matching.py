class SubgraphQueryGenerator(Generator[SubgraphQueryDataset]):
    """Builds the inputs of one subgraph query, in its benchmark's argument order."""

    def __init__(self, benchmark: "SubgraphQueryBenchmark"):
        self._benchmark = benchmark

    @property
    def _is_toy(self) -> bool:
        return self._benchmark.source == "toy"

    @property
    def cacheable(self) -> bool:
        return False

    @property
    def name(self) -> str:
        return f"{self._benchmark.name}_inputs"

    @property
    def pretty_name(self) -> str:
        return f"{self._benchmark.pretty_name} Inputs"

    @property
    def description(self) -> str:
        if self._is_toy:
            return "Small labeled graph queries."
        return (
            "Transforms the G-CARE dataset to the input of subgraph matching"
            " algorithms."
        )

    @property
    def suites(self) -> list[str]:
        return ["test"] if self._is_toy else ["standard"]

    @property
    def concepts(self) -> str:
        return "<ccs2012></ccs2012>"

    @property
    def authors(self) -> list[Contributor]:
        return _AUTHORS

    @property
    def references(self) -> list[Ref]:
        return [] if self._is_toy else [_GCARE_REFERENCE]

    @property
    def ai_disclosure(self) -> str:
        return (
            "No generative AI was used to write the algorithms for the "
            "benchmark function. Generative AI might have been used to "
            "construct the framework, comments and helper functions."
        )

    @property
    def motivation(self) -> str:
        return _MOTIVATION

    @property
    def datasets(self) -> list[SubgraphQueryDataset]:
        return [SubgraphQueryDataset(self._benchmark)]

    def generate(self, dataset: SubgraphQueryDataset):
        benchmark = self._benchmark
        matrix_names = benchmark.matrix_names
        if self._is_toy:
            gt = _TOY_GROUND_TRUTH[benchmark.query_name]
            matrices = _toy_matrices()
            return DataInstance(
                inputs=[matrices[name] for name in matrix_names],
                meta={"name": benchmark.query_name, "gt": gt},
                ref_meta={"gt": gt},
            )
        inputs, gt = _gcare_query_inputs(
            benchmark.subset, benchmark.query_name, matrix_names
        )
        return DataInstance(
            inputs=inputs,
            meta={"name": benchmark.query_name, "gt": gt},
        )


class SubgraphQueryBenchmark(Benchmark, ABC):
    """Counts the matches of one subgraph query with a single einsum.

    Generated subclasses set ``source`` (``"gcare"`` or ``"toy"``), ``subset``,
    ``query_name`` and ``dataset_suites``, and define ``benchmark`` with one
    parameter per query matrix after ``xp`` and ``meta``.
    """

    source: str
    subset: str
    query_name: str
    dataset_suites: list[str] = []

    @property
    def matrix_names(self) -> tuple[str, ...]:
        parameters = inspect.signature(type(self).benchmark).parameters
        return tuple(parameters)[3:]

    @property
    def name(self):
        return f"subgraph_{self.subset}_{_slug(self.query_name)}"

    @property
    def pretty_name(self):
        return f"Subgraph Matching ({self.subset}, {self.query_name})"

    @property
    def description(self):
        return (
            f"Counts matches of the {self.subset} subgraph query "
            f"{self.query_name} using einsum."
        )

    @property
    def suites(self):
        return []

    @property
    def concepts(self) -> str:
        return "<ccs2012></ccs2012>"

    @property
    def authors(self):
        return _AUTHORS

    @property
    def references(self):
        return []

    @property
    def ai_disclosure(self):
        return (
            "No generative AI was used to write the algorithms for the "
            "benchmark function. Generative AI might have been used to "
            "construct the definition of the framework."
        )

    @property
    def motivation(self):
        return _MOTIVATION

    @property
    def generators(self) -> list[Generator]:
        return [SubgraphQueryGenerator(self)]

    def check(self, param):
        super().check(param)
        if not self._ref_meta or "gt" not in self._ref_meta:
            return
        result = to_numpy(self._output[0])
        assert int(np.asarray(result).ravel()[0]) == self._ref_meta["gt"]


