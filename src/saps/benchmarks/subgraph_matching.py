class SubgraphMatchingGCAREGenerator(
    _SubgraphFunctionGenerator, Generator[SubgraphMatchingGCAREDataset]
):
    @property
    def cacheable(self) -> bool:
        return False

    @property
    def description(self) -> str:
        return (
            "Transforms the G-CARE dataset to the input of subgraph matching"
            " algorithms."
        )

    @property
    def suites(self) -> list[str]:
        return ["standard"]

    @property
    def concepts(self) -> str:
        return "<ccs2012></ccs2012>"

    @property
    def authors(self) -> list[Contributor]:
        return [
            Contributor("Taishan Chen", "utallow@bu.edu"),
            Contributor("Kyle Deeds", "kdeeds@bu.edu"),
        ]

    @property
    def references(self) -> list[Ref]:
        return [
            Ref(
                title=(
                    "G-CARE: A Framework for Performance Benchmarking of "
                    "Cardinality Estimation Techniques for Subgraph Matching"
                ),
                authors=[
                    Author("Yeonsu Park"),
                    Author("Seongyun Ko"),
                    Author("Sourav S Bhowmick"),
                    Author("Kyoungmin Kim"),
                    Author("Kijae Hong"),
                    Author("Wook-Shin Han"),
                ],
                year=2020,
                url="https://dl.acm.org/doi/10.1145/3318464.3389702",
            ),
        ]

    @property
    def ai_disclosure(self) -> str:
        return (
            "No generative AI was used to write the algorithms for the "
            "benchmark function. Generative AI might have been used to "
            "construct the framework, comments and helper functions."
        )

    @property
    def motivation(self) -> str:
        return (
            "Subgraph matching and counting are classic problems and widely "
            "used in query evaluations in database systems."
        )

    def generate(self, dataset: SubgraphMatchingGCAREDataset):
        raw_generator = GCAREGraphGenerator()
        raw_dataset = next(
            (ds for ds in raw_generator.datasets if ds.name == dataset.subset_name),
            None,
        )
        if raw_dataset is None:
            raise ValueError(
                f"Dataset {dataset.subset_name!r} is not listed in "
                "GCAREGraphGenerator.datasets."
            )
        graph_problem = raw_generator.cached_generate(raw_dataset)
        graph_meta = graph_problem.meta
        if "queries" not in graph_meta:
            raise RuntimeError(
                f"Cached G-CARE graph {dataset.subset_name!r} has no query metadata. "
                "Refresh it with --cache-datasets --re '^subgraph_gcare_graph$'."
            )
        if dataset.query_name not in graph_meta["queries"]:
            raise ValueError(
                f"Query {dataset.name} is not in the cached G-CARE queries."
            )
        query = graph_meta["queries"][dataset.query_name]
        graph_matrices = dict(
            zip(graph_meta["matrix_names"], graph_problem.inputs, strict=True)
        )
        size = graph_meta["max_vid"] + 1
        inputs = []
        for name in query["matrix_names"]:
            if name in graph_matrices:
                tensor = graph_matrices[name]
            elif name.startswith("P"):
                tensor = CustomTensor(
                    (size,),
                    1,
                    level=SparseLevel(
                        1,
                        ElementLevel(np.array([1])),
                        (np.array([int(name[1:])]),),
                    ),
                )
            elif name.startswith("V"):
                tensor = CustomTensor(
                    (size,),
                    1,
                    level=SparseLevel(1, ElementLevel(np.array([0])), (np.array([0]),)),
                )
            elif name.startswith("E"):
                tensor = COORMatrix(
                    (size, size),
                    1,
                    indices_0=np.array([0]),
                    indices_1=np.array([0]),
                    values=np.array([0]),
                )
            else:
                raise ValueError(f"Cached G-CARE graph is missing matrix {name!r}")
            inputs.append(tensor)
        return DataInstance(
            inputs=inputs,
            meta={
                "expr": query["expr"],
                "gt": query["gt"],
                "name": dataset.query_name,
                "matrix_names": query["matrix_names"],
            },
        )


