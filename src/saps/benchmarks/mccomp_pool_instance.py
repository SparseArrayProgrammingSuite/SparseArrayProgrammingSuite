class MCCompPoolDataset(Dataset):
    """An instance from the MC 2020-2024 archives on Zenodo.

    ``source_path`` is its file in the unpacked archives. The name drops the
    archive's directory, whose year and track the file or benchmark set name
    repeats, and the file's suffixes, and spells its other dots as underscores.
    """

    def __init__(self, source_path: str, *, suites: list[str] | None = None):
        self.source_path = source_path
        self._suites = suites or []

    @property
    def name(self) -> str:
        return (
            self.source_path.split("/", 1)[1]
            .removesuffix(".xz")
            .removesuffix(".cnf")
            .replace(".", "_")
        )

    @property
    def pretty_name(self) -> str:
        return self.name

    @property
    def description(self) -> str:
        return f"Model Counting Competition instance {self.source_path}."

    @property
    def suites(self) -> list[str]:
        return self._suites

    @property
    def concepts(self) -> str:
        return "<ccs2012></ccs2012>"

    @property
    def metadata(self) -> dict[str, Any]:
        data = super().metadata
        data.update(
            {
                "source_path": self.source_path,
                "source_url": mccomp_pool_record_url(self.source_path),
            }
        )
        return data


