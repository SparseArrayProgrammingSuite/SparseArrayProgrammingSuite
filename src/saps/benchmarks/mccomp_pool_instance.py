class MCCompPoolInstanceGenerator(Generator[MCCompPoolDataset]):
    """Downloads and caches the listed MC 2020-2024 pool instances."""

    @property
    def name(self) -> str:
        return "mccomp_pool_instance"

    @property
    def pretty_name(self) -> str:
        return "MCComp Pool Instances"

    @property
    def description(self) -> str:
        return (
            "Downloads the instance archives of the Model Counting Competitions "
            "2020-2024 from Zenodo and stores the text of each listed DIMACS CNF "
            "instance."
        )

    @property
    def suites(self) -> list[str]:
        # --cache-datasets prepares the shell suite.
        return ["shell"]

    @property
    def concepts(self) -> str:
        return "<ccs2012></ccs2012>"

    @property
    def authors(self) -> list[Contributor]:
        return []

    @property
    def references(self) -> list[Ref]:
        return [
            Ref(
                title="The Model Counting Competition 2020",
                authors=[
                    Author("Johannes K. Fichte"),
                    Author("Markus Hecher"),
                    Author("Florim Hamiti"),
                ],
                journal="ACM Journal of Experimental Algorithmics",
                year=2021,
                url="https://doi.org/10.1145/3459080",
                doi="10.1145/3459080",
            ),
            Ref(
                title="The Model Counting Competitions 2021-2023",
                authors=[Author("Johannes K. Fichte"), Author("Markus Hecher")],
                year=2025,
                url="https://arxiv.org/abs/2504.13842",
            ),
        ]

    @property
    def ai_disclosure(self) -> str:
        return "Generative AI was used to implement this generator."

    @property
    def motivation(self) -> str:
        return (
            "The competition organizers published every instance submitted to "
            "them, not only those they selected, so the pools hold small instances "
            "from the same applications as the competitions' large ones."
        )

    @property
    def license(self) -> License | None:
        return licenses.MCCOMP_POOL

    @property
    def datasets(self) -> list[MCCompPoolDataset]:
        return MCCOMP_POOL_MODEL_COUNTING_INSTANCES + MCCOMP_POOL_WEIGHTED_INSTANCES

    def generate(self, dataset: MCCompPoolDataset) -> DataInstance:
        path = download_mccomp_pool_instance(dataset.source_path)
        with lzma.open(path, "rt", encoding="utf-8", errors="replace") as file:
            text = file.read()
        return DataInstance(
            inputs=[from_numpy(np.frombuffer(text.encode("utf-8"), dtype=np.uint8))],
            meta={
                "source_path": dataset.source_path,
                "source_url": mccomp_pool_record_url(dataset.source_path),
            },
        )


class MCCompPoolInstanceShellBenchmark(ShellBenchmark):
    @property
    def generator(self) -> Generator:
        return MCCompPoolInstanceGenerator()


def fetch_mccomp_pool_instance(source_path: str) -> DataInstance:
    """Fetch a listed pool instance via the shared `MCCompPoolInstanceGenerator`.

    `.inputs[0]` holds the instance file's text as UTF-8 bytes.
    """
    generator = MCCompPoolInstanceGenerator()
    for dataset in generator.datasets:
        if dataset.source_path == source_path:
            return generator.cached_generate(dataset)
    raise ValueError(f"Unlisted MC competition pool instance: {source_path!r}")
