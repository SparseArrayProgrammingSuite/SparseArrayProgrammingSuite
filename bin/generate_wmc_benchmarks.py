#!/usr/bin/env python3
"""Generate saps.benchmarks.weighted_model_counting_formulas: one class per formula.

Parses every formula listed by ``wmc_formulas()`` (the inline test formulas and
the MCComp Track4 instances) and writes a module in which each formula's
``benchmark`` takes ``B, W1, ..., Wn`` as explicit parameters and evaluates that
formula's einsum.
"""

from __future__ import annotations

import argparse
from pathlib import Path

from saps.benchmarks.weighted_model_counting import (
    _default_weighted_total,
    clauses_to_einsum,
    parse_format,
    wmc_formulas,
)
from saps.codegen import (
    render_einsum_return,
    render_signature,
    require_unique,
    write_or_check,
)

OUTPUT = (
    Path(__file__).resolve().parents[1]
    / "src/saps/benchmarks/weighted_model_counting_formulas.py"
)

DOCSTRING = '''\
"""Per-formula weighted model counting benchmarks.

Generated by bin/generate_wmc_benchmarks.py from the formulas listed by
saps.benchmarks.weighted_model_counting.wmc_formulas. Do not edit by hand.
"""
'''
BASE_IMPORT = (
    "from saps.benchmarks.weighted_model_counting import "
    "WeightedModelCountingBenchmark\n"
)


def _render_class(source: str, dataset_name: str, cnf_text: str) -> tuple[str, bool]:
    """Return the class source and whether it needs numpy."""
    num_vars, clauses, weights = parse_format(cnf_text)
    expr = clauses_to_einsum(clauses, num_vars)
    params = ["B", *(f"W{i}" for i in range(1, num_vars + 1))]
    if expr is None:
        total = _default_weighted_total(weights, num_vars)
        body = [f"        return xp.array({total!r}, dtype=np.float64)"]
    else:
        body = render_einsum_return(expr, params)
    lines = [
        f"class WMC_{dataset_name}(WeightedModelCountingBenchmark):",
        f'    source = "{source}"',
        f'    dataset_name = "{dataset_name}"',
        "",
        *render_signature(params),
        *body,
    ]
    return "\n".join(lines) + "\n", expr is None


def render() -> str:
    formulas = wmc_formulas()
    require_unique((dataset.name for _, dataset, _ in formulas), "dataset names")
    rendered = [
        _render_class(source, dataset.name, cnf_text)
        for source, dataset, cnf_text in formulas
    ]
    imports = "\n" + ("import numpy as np\n\n" if any(n for _, n in rendered) else "")
    return (
        DOCSTRING + imports + BASE_IMPORT + "".join(f"\n\n{cls}" for cls, _ in rendered)
    )


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--check",
        action="store_true",
        help="Exit non-zero if the committed module differs from a fresh render.",
    )
    parser.add_argument("-o", "--output", default=OUTPUT, type=Path)
    args = parser.parse_args()
    return write_or_check(args.output, render(), args.check)


if __name__ == "__main__":
    raise SystemExit(main())
