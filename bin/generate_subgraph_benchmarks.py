#!/usr/bin/env python3
"""Generate saps.benchmarks.subgraph_queries: one benchmark class per query.

Reads the query inventory (``TOY_QUERIES`` and ``GCARE_QUERIES`` in
saps.benchmarks.subgraph_matching) and each G-CARE query's einsum expression
from its cached source graph, then writes a module in which every query's
``benchmark`` takes that query's matrices as explicit parameters.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

from saps.benchmarks.subgraph_matching import (
    GCARE_QUERIES,
    TOY_QUERIES,
    GCareGraphGenerator,
)
from saps.codegen import (
    render_einsum_return,
    render_signature,
    require_unique,
    write_or_check,
)

OUTPUT = Path(__file__).resolve().parents[1] / "src/saps/benchmarks/subgraph_queries.py"

HEADER = '''\
"""Per-query subgraph matching benchmarks.

Generated by bin/generate_subgraph_benchmarks.py from the query inventory in
saps.benchmarks.subgraph_matching. Do not edit by hand.
"""

from saps.benchmarks.subgraph_matching import SubgraphQueryBenchmark
'''


def _class_name(subset: str, query_name: str) -> str:
    return f"Subgraph_{subset}_{re.sub(r'[^0-9A-Za-z]+', '_', query_name)}"


def _render_class(
    source: str,
    subset: str,
    query_name: str,
    suites: list[str],
    expr: str,
    params: list[str],
) -> str:
    suites_src = "[" + ", ".join(f'"{suite}"' for suite in suites) + "]"
    lines = [
        f"class {_class_name(subset, query_name)}(SubgraphQueryBenchmark):",
        f'    source = "{source}"',
        f'    subset = "{subset}"',
        f'    query_name = "{query_name}"',
        f"    dataset_suites = {suites_src}",
        "",
        *render_signature(params),
        *render_einsum_return(expr, params, delimiter=" * "),
    ]
    return "\n".join(lines) + "\n"


def _gcare_queries(subset: str) -> dict:
    generator = GCareGraphGenerator()
    dataset = next(ds for ds in generator.datasets if ds.name == subset)
    return generator.cached_generate(dataset).meta["queries"]


def render() -> str:
    classes = [
        _render_class("toy", "toy", name, ["test"], expr, list(names))
        for name, expr, names, _ in TOY_QUERIES
    ]
    class_names = [_class_name("toy", name) for name, *_ in TOY_QUERIES]
    for subset, rows in GCARE_QUERIES.items():
        print(f"loading G-CARE {subset} queries", file=sys.stderr)
        queries = _gcare_queries(subset)
        for query_name, suites in rows:
            if query_name not in queries:
                raise ValueError(f"{subset}/{query_name} is not a cached G-CARE query")
            query = queries[query_name]
            classes.append(
                _render_class(
                    "gcare",
                    subset,
                    query_name,
                    suites,
                    query["expr"],
                    list(query["matrix_names"]),
                )
            )
            class_names.append(_class_name(subset, query_name))
    require_unique(class_names, "class names")
    return HEADER + "".join(f"\n\n{cls}" for cls in classes)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--check",
        action="store_true",
        help="Exit non-zero if the committed module differs from a fresh render.",
    )
    parser.add_argument("-o", "--output", default=OUTPUT, type=Path)
    args = parser.parse_args()
    return write_or_check(args.output, render(), args.check)


if __name__ == "__main__":
    raise SystemExit(main())
